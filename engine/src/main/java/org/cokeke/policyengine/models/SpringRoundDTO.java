package org.cokeke.policyengine.models; 

public record SpringRoundDTO(
    int currentMonth,
    String stateId,
    String stateName,
    double population,
    double productivity,
    double publicCapital,
    double priceLevel,
    double lastInflation,
    double householdWealth,
    double governmentDebt,
    double stability,
    double taxRate,
    double spendingShare,
    double investmentShare,
    double transferShare,
    double output,
    double outputGap,
    double unemployment,
    double federalTax,
    double allocation,
    double spending,
    double transfers,
    double interest,
    String policy,
    double resourcePrice,
    double netWorth,
    double federalTaxShare,
    double roundScore,
    int roundRank
    ) {

    public SpringRoundDTO(StateEconomy state, StateFlows sFlows, FederalEconomy fed) {
        this(
            state.currentMonth(),
            state.id().toString(),
            state.name(),
            state.population(),
            state.productivity(),
            state.publicCapital(),
            state.priceLevel(),
            state.lastInflation(),
            state.householdWealth(),
            state.governmentDebt(),
            state.stability(),
            state.taxRate(),
            state.spendingShare(),
            state.investmentShare(),
            state.transferShare(),
            sFlows.output(),
            sFlows.outputGap(),
            sFlows.unemployment(),
            sFlows.federalTax(),
            sFlows.allocation(),
            sFlows.spending(),
            sFlows.transfers(),
            sFlows.interest(),
            sFlows.policy().toString(),
            fed.resourcePrice(),
            fed.netWorth(),
            fed.federalTaxShare(),
            state.roundScore(),
            state.roundRank()
        );
    }
}